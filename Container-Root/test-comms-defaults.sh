grep -q "Posting to real Slack from the comms UI: not at this engine pin" "${ENV_ROOT}/docs/comms/README.md" 2>/dev/null \
	|| fail "docs/comms/README.md does not state that the comms UI cannot post to real Slack at this pin"
echo "ok 7 - the pinned slack adapter has no send path, and docs/comms/README.md says the comms UI cannot post to real Slack at this pin"

# --- 8. the build-time engine patches are applied, and the thread-answered one took effect ---
N8=0
for PATCH in "${SETUP_DIR}"/comms-patches/*.patch; do
	[ -f "${PATCH}" ] || continue
	N8=$((N8 + 1))
	git -C "${COMMS_HOME}" apply --check --reverse "${PATCH}" > /dev/null 2>&1 \
		|| fail "engine patch $(basename "${PATCH}") is not applied on ${COMMS_HOME} (git apply --check --reverse fails): install-comms.sh did not apply it, or the pin moved under it"
done
[ "${N8}" -ge 1 ] || fail "no engine patch under ${SETUP_DIR}/comms-patches/ - this check expects 0001-thread-answered-at-ingest.patch until the engine pin moves past its merge"
COMMS_SETTINGS=${D}/migrate-v1/settings.json python3 - << 'EOF' || fail "the thread-answered engine patch did not take effect"

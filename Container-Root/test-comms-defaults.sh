echo "ok 6a - Reply -> Stage -> Send on the demo ask marks it answered with the outbox key"
COMMS_SETTINGS=${D}/migrate-v1/settings.json python3 - << 'EOF' || fail "a thread reply from another user did not close its ask"
import contextlib, importlib.util, io, os, sqlite3, sys
home = os.environ["COMMS_HOME"]
sys.path.insert(0, home)
from core.config import load
from core.dashboard import snapshot
SETTINGS = os.environ["COMMS_SETTINGS"]
cfg = load(SETTINGS)
spec = importlib.util.spec_from_file_location("scheduler", home + "/scripts/scheduler.py")
scheduler = importlib.util.module_from_spec(spec)
spec.loader.exec_module(scheduler)

def cycle(messages):
    """One run of the engine's own scheduler (scripts/scheduler.py --once), with the fake
    adapter's dry-run seed() hook planting these messages instead of the demo message."""
    def seed(adapters, cfg):
        for inst in cfg.instances:
            adapters[inst.name].seed([dict(m, channel_type=inst.adapter) for m in messages])
    scheduler.seed_demo = seed
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        rc = scheduler.main(["--config", SETTINGS, "--once", "--seed-demo"])
    assert rc == 0, f"scheduler exit {rc}: {out.getvalue()}"
    return out.getvalue()

def row(ts):
    conn = sqlite3.connect(f"file:{cfg.journal_path}?mode=ro", uri=True)
    try:
        return conn.execute("SELECT responded_at, response_key, kind FROM journal "
                            "WHERE channel='C_DEMO' AND ts=?", (ts,)).fetchone()
    finally:
        conn.close()

assert row("1.0")[0] is None, "the demo ask is not open before the thread reply"
# a later top-level message moves the history cursor past the reply that comes next
cycle([{"channel_id": "C_DEMO", "sender_id": "U_DEMO", "sender_name": "quickstart-demo",
        "ts": "3.0", "text": "FYI: the demo channel is quiet today."}])
# the reply sits in the ask's thread, below the cursor: the history poll does not serve it
out = cycle([{"channel_id": "C_DEMO", "sender_id": "U_TEAMMATE", "sender_name": "teammate",
              "ts": "2.0", "text": "Reviewed it - looks good.", "thread_id": "1.0"}])
print("  " + out.strip().replace("\n", "\n  "))
assert row("2.0") is not None, "the thread reply was not listed (no journal row)"
assert row("1.0")[:2] != (None, None) and row("1.0")[1] == "thread-reply:2.0", \
    f"the ask was not tied to the thread reply: {row('1.0')}"
open_asks = [a["ts"] for a in snapshot(cfg.journal_path, {})["attention"] if a["severity"] == "unanswered"]
assert open_asks == [], f"open asks remain: {open_asks}"
EOF
echo "ok 6b - a reply in the ask's thread from another user is listed and closes the ask in one scheduler cycle"

# --- 7. the docs' read-only real-Slack statement holds at this pin ---
python3 - << 'EOF' || fail "the pinned engine's slack adapter is not read-only"

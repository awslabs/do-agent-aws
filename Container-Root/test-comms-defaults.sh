assert not at.exception, at.exception
responded_at, response_key = ask()
assert responded_at is not None, "the demo ask is still UNANSWERED after its reply was sent"
assert response_key == key, f"the response key {response_key!r} is not the outbox key {key!r}"
open_asks = [a for a in snapshot(cfg.journal_path, {})["attention"] if a["severity"] == "unanswered"]
assert open_asks == [], f"the answered ask is still in the unanswered queue: {open_asks}"
print(f"  demo ask C_DEMO 1.0 answered by the outbox key {key[:12]}...")

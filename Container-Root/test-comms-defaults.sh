# Unit test of the comms out-of-the-box contract: the watcher is on by default and idles on the
# generated demo settings, settings.json gets its compose form (fresh, or migrated from an
# unmodified default an earlier start generated) while an edited file is never rewritten, the
# pinned engine marks answered asks answered, and the pinned Slack adapter has no send path, as
# docs/comms/README.md states. Fully OFFLINE: everything runs against the
# communication engine's credential-free fake adapter; no real Slack/Telegram/email call is made.
#
# Properties proven (each check FAILS if the property is removed):
#   1. the touched scripts parse (bash -n)
#   2. the COMMS_WATCH_ENABLED that .env ships drives startup.sh: with it the watcher is RUNNING
#      on the generated demo settings (comms-watch-status.sh exits 0) and idles over >= 2
#      cycles - the same pid, polled=0 each cycle, no Traceback/REFUSED line - at the demo
#      channel's 60 s: the seeded demo ask is unanswered, so the engine polls at the base
#      interval, and the second cycle comes >= 50 s after the first (at the example's 15 s it
#      came after 15 s, 4 cycle lines a minute). A planted COMMS_WATCH_ENABLED=false in .env
#      fails this check.
#   3. a fresh state directory with the write gate on: the demo channel at reply_policy
#      'staged', polled every 60 s, and the compose form rendered
#   4. the defaults that earlier comms-ui-start.sh versions generated - read-only (60d75cc; and
#      c93d826 .. 3defadd with the write gate off), which render no compose form, and
#      composable at the example's 15 s (c93d826 .. 3defadd with the write gate on) - are
#      regenerated by a start with the write gate on: it says so, the file equals the fresh
#      default, and the compose form renders
#   5. an edited read-only file is left byte-identical, the start prints one notice line naming
#      reply_policy and where to change it in the comms UI, and the compose form stays absent
#   6. answered state at the pinned engine: Reply on the demo ask -> Stage -> Send marks it
#      answered with the outbox key; and a reply in the ask's thread from another user, which
#      the history poll does not serve, is stored, journaled and ties the ask
#      ('thread-reply:<ts>') in one scheduler cycle
#   7. the pinned engine's Slack adapter has no send() and declares send=False, and
#      docs/comms/README.md says the comms UI cannot post to real Slack at this pin (a pending
#      engine PR adds it; this check then fails, and the docs are due)
#   8. the build-time engine patches of setup/comms-patches/ are applied on the installed engine (each
#      reverse-applies cleanly; a patch that is not applied, or a pin that moved under one, fails here), and
#      the one shipped today took effect: a message that has a thread is answered - an ask the fake adapter
#      serves with a reply from someone else under it is tied in the SAME scheduler cycle that polls it, with
#      the ingest key (thread-reply:summary:<replier>; the sweep's would be thread-reply:<ts>) and counted on the
#      cycle line, and the config loader reads instances[].threaded_is_answered
# Uses test-local state directories (/tmp/comms-defaults*); does not disturb /wd.

D=/tmp/comms-defaults
rm -rf "${D:?}"
mkdir -p ${D}

BASE_DIR="$(cd "$(dirname "$0")" && pwd)"
AGENT_DIR="${BASE_DIR%/}/agent"
SETUP_DIR="${BASE_DIR%/}/setup"
export COMMS_HOME=${COMMS_HOME:-/opt/comms}
export COMMS_PYTHON=${COMMS_PYTHON:-/opt/comms-venv/bin/python}  # streamlit's own Python 3.12 environment (setup/install-comms.sh)
# The UI daemons this test starts answer at / on test-local loopback ports
export COMMS_UI_BASE_PATH=
export COMMS_UI_LISTEN_HOST=127.0.0.1
export COMMS_DEMO_SEED=true

STARTUP_PID=""
fail()
{
	echo "Test-comms-defaults FAILED: $1"
	[ -n "${STARTUP_PID}" ] && kill "${STARTUP_PID}" 2>/dev/null
	for S in "${D}"/*/; do
		COMMS_DIR=${S%/} "${AGENT_DIR}/comms-watch-stop.sh" > /dev/null 2>&1
		COMMS_DIR=${S%/} "${AGENT_DIR}/comms-ui-stop.sh" > /dev/null 2>&1
	done
	UI_DIR=${D}/ui "${AGENT_DIR}/ui-stop.sh" > /dev/null 2>&1
	exit 1
}

# --- 1. syntax ---
for S in "${AGENT_DIR}/comms-ui-start.sh" "${AGENT_DIR}/comms-watch-start.sh" \
         "${AGENT_DIR}/comms-watch-status.sh" "${SETUP_DIR}/install-comms.sh" "${BASE_DIR}/startup.sh"; do
	bash -n "${S}" || fail "bash -n ${S}"
done
echo "ok 1 - syntax"

if [ ! -f "${COMMS_HOME}/scripts/scheduler.py" ] || [ ! -f "${COMMS_HOME}/scripts/dashboard_write.py" ] \
	|| ! command -v python3 > /dev/null; then
	echo "Test-comms-defaults skipped: communication engine not installed under ${COMMS_HOME} (run setup/install-comms.sh)"
	exit 0
fi
ENV_FILE=""
for CAND in /do-agent-aws/.env "${BASE_DIR}/../.env"; do
	[ -f "${CAND}" ] && ENV_FILE="$(cd "$(dirname "${CAND}")" && pwd)/.env" && break
done
if [ -z "${ENV_FILE}" ]; then
	echo "Test-comms-defaults skipped: .env not found (expected the repo mounted at /do-agent-aws)"
	exit 0
fi
ENV_ROOT="$(dirname "${ENV_FILE}")"

# compose_form <settings> <present|absent> - render the dashboard through the real UI (streamlit
# AppTest) with the write gate on and assert whether the compose form exists
compose_form()
{
	COMMS_SETTINGS="$1" COMMS_UI_WRITE_ENABLED=true EXPECT="$2" "${COMMS_PYTHON}" - << 'EOF'
import os, sys
sys.path.insert(0, os.environ["COMMS_HOME"])
from streamlit.testing.v1 import AppTest
at = AppTest.from_file(os.environ["COMMS_HOME"] + "/scripts/dashboard.py", default_timeout=120).run()
assert not at.exception, at.exception
form = [b for b in at.button if b.key and b.key.startswith("FormSubmitter:compose")]
if os.environ["EXPECT"] == "present":
    assert len(form) == 1, "the compose form is absent"
else:
    assert not form, "a compose form rendered"
    assert any("no channel is composable" in str(i.value) for i in at.info), \
        "the dashboard does not say why there is no compose form"
EOF
}

# --- 2. the shipped default starts the watcher, and it idles on the demo settings ---
WATCH_DEFAULT=$(cd "${ENV_ROOT}" && bash -c 'source ./.env > /dev/null 2>&1; echo "${COMMS_WATCH_ENABLED}"')
echo "  .env ships COMMS_WATCH_ENABLED=${WATCH_DEFAULT}"
S2=${D}/startup
# startup.sh exactly as shipped, with the comms UI on (it generates settings.json and seeds the
# demo on the first start, then the watcher starts) and every other startup feature off - every other UI by its flag
# (the ones ui-start.sh added since this list was first written too: a LogLearner dashboard left running here, on its
# default port and indexing into the default /wd/loglearner, was what a later test's write guard caught in a sequential
# run of the suite), and whatever it started is stopped with the test's UI_DIR below and in fail; the state a start
# writes goes under the test's own directory, not /wd (the starter repository, the LogLearner bank, the knowledge copy,
# the Deck's inputs, the capture log - test6 check 11 does the same)
AUTONOMY_LOOP=false SLACK_CHAT_ENABLED=false AGENT_TMUX_SESSION=false SUPERVISOR=false UI_START=true UI_DIR=${D}/ui \
UI_HEADLAMP=false UI_HINDSIGHT=false UI_VIBE_KANBAN=false UI_HOME=false UI_TMUX=false UI_TMUX_AGENT=false \
UI_CLAUDE_MEM=false UI_LOGLEARNER=false UI_CHAT=false UI_LOOP=false UI_LOOP_DECK=false UI_FILES=false \
STARTER_REPO_ROOT=${D}/wd LOGLEARNER_STATE=${D}/loglearner KNOWLEDGE_DIR=${D}/knowledge LOOP_DECK_DATA_DIR=${D}/loop-deck TMUX_AGENT_HOME=${D}/tmux-agent-home \
COMMS_UI_ENABLED=true COMMS_UI_WRITE_ENABLED=true COMMS_UI_PORT=8605 COMMS_DIR=${S2} \
COMMS_WATCH_ENABLED="${WATCH_DEFAULT}" sh "${BASE_DIR}/startup.sh" > ${D}/startup.log 2>&1 &
STARTUP_PID=$!
# comms-watch-start.sh reports either way ("started" or "did not start") once it has checked
for _ in $(seq 1 30); do
	grep -qE "comms-watch: (started|did not start|no )" ${D}/startup.log 2>/dev/null && break
	sleep 1
done
[ -f ${S2}/watch.pid ] || fail "no watcher started with the shipped COMMS_WATCH_ENABLED=${WATCH_DEFAULT}: $(cat ${D}/startup.log)"
WATCH_PID=$(cat ${S2}/watch.pid)
# the first cycle fires at once; time the second
T1=""; T2=""
for _ in $(seq 1 150); do
	N=$(grep -c '^cycle:' ${S2}/watch.log 2>/dev/null)
	[ -z "${T1}" ] && [ "${N:-0}" -ge 1 ] && T1=$(date +%s)
	[ "${N:-0}" -ge 2 ] && T2=$(date +%s) && break
	sleep 1
done
STATUS=$(COMMS_DIR=${S2} COMMS_WATCH_ENABLED="${WATCH_DEFAULT}" "${AGENT_DIR}/comms-watch-status.sh"); RC=$?
while IFS= read -r LINE; do echo "  ${LINE}"; done <<< "${STATUS}"
[ ${RC} -eq 0 ] || fail "comms-watch-status.sh exits ${RC} with the shipped default"
echo "${STATUS}" | grep -q "RUNNING (pid ${WATCH_PID})" || fail "comms-watch-status.sh does not report the watcher RUNNING"
CYCLES=$(grep -c '^cycle:' ${S2}/watch.log)
if [ "${CYCLES}" -lt 2 ] || [ -z "${T1}" ] || [ -z "${T2}" ]; then
	fail "fewer than 2 watcher cycles in 150s: $(cat ${S2}/watch.log)"
fi
GAP=$((T2 - T1))
[ ${GAP} -ge 50 ] || fail "the second watcher cycle came ${GAP}s after the first: the demo channel's poll interval is not 60 s (at 15 s the log grows by 4 cycle lines a minute while the demo ask is open)"
grep '^cycle:' ${S2}/watch.log | grep -qv 'polled=0 ' && fail "a cycle polled messages on the idle demo settings: $(cat ${S2}/watch.log)"
grep -qE 'Traceback|REFUSED' ${S2}/watch.log && fail "the watcher log has an error: $(cat ${S2}/watch.log)"
if [ "$(cat ${S2}/watch.pid)" != "${WATCH_PID}" ] || [ ! -d "/proc/${WATCH_PID}" ]; then
	fail "the watcher did not stay up as pid ${WATCH_PID}"
fi
sed 's/^/  watch.log: /' ${S2}/watch.log
kill "${STARTUP_PID}" 2>/dev/null; STARTUP_PID=""
COMMS_DIR=${S2} "${AGENT_DIR}/comms-watch-stop.sh" > /dev/null
COMMS_DIR=${S2} "${AGENT_DIR}/comms-ui-stop.sh" > /dev/null
UI_DIR=${D}/ui "${AGENT_DIR}/ui-stop.sh" > /dev/null 2>&1
[ -d "/proc/${WATCH_PID}" ] && fail "the watcher survived its stop"
echo "ok 2 - the shipped COMMS_WATCH_ENABLED=${WATCH_DEFAULT} starts the watcher; it idled ${CYCLES} cycles on the demo settings, ${GAP}s apart (same pid, polled=0, no error)"

# --- 3. a fresh state directory: the demo channel composable, the compose form rendered ---
python3 - "${S2}/settings.json" << 'EOF' || fail "the fresh settings.json is not the composable demo default"
import json, sys
cfg = json.load(open(sys.argv[1]))
assert [i.get("adapter") for i in cfg["instances"]] == ["fake"], cfg["instances"]
chans = [(ch.get("reply_policy"), ch.get("poll_interval_s")) for i in cfg["instances"] for ch in i.get("channels", [])]
assert chans == [("staged", 60)], chans
EOF
compose_form ${S2}/settings.json present || fail "fresh settings: compose form"
echo "ok 3 - fresh state: the demo channel at reply_policy staged, polled every 60 s, compose form rendered"

# --- 4. an unmodified default an earlier start generated is regenerated ---
# The planted files are the content those scripts wrote: their note (verbatim) and the fake
# instance of the engine's settings.example.json - the demo channel at 'never' and 15 s, or at
# 'staged' (c93d826 .. 3defadd with the write gate on).
NOTE_HEAD="Generated by /agent/comms-ui-start.sh with only the credential-free fake adapter instance kept, so the dashboard works out of the box. To watch real channels, replace this file following settings.example.json in ${COMMS_HOME} and docs/comms/README.md - auth values are env: references to YOUR tokens; never put literal credentials in this file."
NOTE_V2="${NOTE_HEAD} Channels are generated at reply_policy 'staged' (composable, click-gated) when COMMS_UI_WRITE_ENABLED=true at first start, 'never' (read-only) otherwise; this file is generated once - edit it to change policies later."
plant()
{
	# plant <dir> <note> [<poll_interval_s override>] [staged] - an older start's default
	mkdir -p "$1"
	NOTE="$2" OUT="$1/settings.json" EDIT="$3" STAGED="$4" python3 - << 'EOF'
import json, os, pathlib
home = pathlib.Path(os.environ["COMMS_HOME"])
example = json.loads((home / "settings.example.json").read_text())
settings = {"_note": os.environ["NOTE"],
            "engine": {"state_dir": "state", "channels_dir": str(home / "channels"),
                       "store": "state/messages.db", "journal": "state/journal.db",
                       "outbox": "state/outbox.db"},
            "instances": [i for i in example["instances"] if i.get("adapter") == "fake"]}
if os.environ.get("EDIT"):
    settings["instances"][0]["channels"][0]["poll_interval_s"] = int(os.environ["EDIT"])
if os.environ.get("STAGED"):
    settings["instances"][0]["channels"][0]["reply_policy"] = "staged"
pathlib.Path(os.environ["OUT"]).write_text(json.dumps(settings, indent=2) + "\n")
EOF
}
PORT=8606
for V in v1 v2 v2-staged; do
	S4=${D}/migrate-${V}
	case "${V}" in
	v1)        plant ${S4} "${NOTE_HEAD}"; WHY="the demo channel at reply_policy 'never', so the dashboard had no compose form" ;;
	v2)        plant ${S4} "${NOTE_V2}"; WHY="the demo channel at reply_policy 'never', so the dashboard had no compose form" ;;
	v2-staged) plant ${S4} "${NOTE_V2}" "" staged; WHY="the demo channel polled every 15 s" ;;
	esac
	if [ "${V}" != "v2-staged" ]; then
		compose_form ${S4}/settings.json absent || fail "${V}: the planted read-only default already renders a compose form - not a valid plant"
	fi
	OUT=$(COMMS_DIR=${S4} COMMS_UI_PORT=${PORT} COMMS_UI_WRITE_ENABLED=true "${AGENT_DIR}/comms-ui-start.sh" 2>&1) \
		|| fail "${V}: comms-ui-start.sh: ${OUT}"
	COMMS_DIR=${S4} "${AGENT_DIR}/comms-ui-stop.sh" > /dev/null
	compose_form ${S4}/settings.json present || fail "${V}: compose form after the start"
	echo "${OUT}" | grep "comms-ui: migrated" | sed 's/^/  /'
	echo "${OUT}" | grep -qF "comms-ui: migrated ${S4}/settings.json - it was the unmodified default an earlier start generated (${WHY})" \
		|| fail "${V}: the start did not say it migrated the file: ${OUT}"
	cmp -s ${S4}/settings.json ${S2}/settings.json || fail "${V}: the migrated file differs from the fresh default"
	PORT=$((PORT + 1))
done
echo "ok 4 - the defaults of 60d75cc and c93d826..3defadd (read-only: no compose form; staged at 15 s) are regenerated at start as the fresh default; compose form rendered"

# --- 5. an edited read-only file is never rewritten; one line says what to change and where ---
S5=${D}/edited
plant ${S5} "${NOTE_V2}" 60
SUM_BEFORE=$(sha256sum ${S5}/settings.json | cut -d' ' -f1)
OUT=$(COMMS_DIR=${S5} COMMS_UI_PORT=${PORT} COMMS_UI_WRITE_ENABLED=true "${AGENT_DIR}/comms-ui-start.sh" 2>&1) \
	|| fail "edited: comms-ui-start.sh: ${OUT}"
COMMS_DIR=${S5} "${AGENT_DIR}/comms-ui-stop.sh" > /dev/null
[ "$(sha256sum ${S5}/settings.json | cut -d' ' -f1)" = "${SUM_BEFORE}" ] || fail "edited: the start rewrote an edited settings.json"
echo "${OUT}" | grep -q "comms-ui: migrated" && fail "edited: the start claims a migration"
NOTICE=$(echo "${OUT}" | grep "was edited, so it is left as it is")
echo "  ${NOTICE}"
[ "$(echo "${NOTICE}" | grep -c .)" = "1" ] || fail "edited: expected exactly one notice line, got: ${OUT}"
echo "${NOTICE}" | grep -q "reply_policy 'never' on example-dry-run C_DEMO" || fail "edited: the notice does not name the setting and the channel"
echo "${NOTICE}" | grep -q "connections & monitored channels > edit monitored channel" || fail "edited: the notice does not say where to change it in the comms UI"
compose_form ${S5}/settings.json absent || fail "edited: compose form"
echo "ok 5 - an edited file: byte-identical after start, one notice line naming reply_policy and the config UI, no compose form"

# --- 6. answered state at the pinned engine ---
COMMS_SETTINGS=${S2}/settings.json COMMS_UI_WRITE_ENABLED=true "${COMMS_PYTHON}" - << 'EOF' || fail "Reply -> Stage -> Send did not mark the demo ask answered"
import os, sqlite3, sys
sys.path.insert(0, os.environ["COMMS_HOME"])
from streamlit.testing.v1 import AppTest
from core.config import load
from core.dashboard import snapshot
cfg = load(os.environ["COMMS_SETTINGS"])

def ask():
    conn = sqlite3.connect(f"file:{cfg.journal_path}?mode=ro", uri=True)
    try:
        return conn.execute("SELECT responded_at, response_key FROM journal "
                            "WHERE channel='C_DEMO' AND ts='1.0'").fetchone()
    finally:
        conn.close()

def run():
    return AppTest.from_file(os.environ["COMMS_HOME"] + "/scripts/dashboard.py",
                             default_timeout=120).run()

assert ask() == (None, None), f"the demo ask is not open before the reply: {ask()}"
at = run()
reply = [b for b in at.button if b.label == "Reply" and b.key and "C_DEMO" in b.key and "1.0" in b.key]
assert len(reply) == 1, "the open demo ask has no Reply button"
at = reply[0].click().run()
at.text_area[0].input("[test-comms-defaults] reviewed, thanks")
sub = [b for b in at.button if b.key and b.key.startswith("FormSubmitter:compose")]
assert len(sub) == 1, "no compose form after Reply"
at = sub[0].click().run()
assert not at.exception, at.exception
assert ask()[0] is None, "STAGING marked the ask answered - a draft is not an answer"
send = [b for b in at.button if b.key and b.key.startswith("send-")]
assert len(send) == 1, "the staged reply has no Send button"

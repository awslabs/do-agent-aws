# conversations spoke — ONE cycle of the communication engine's reference loop: poll the configured Slack
# channels, classify and journal what arrived, sweep the open asks' threads, apply the DM
# answered-state, escalate unattended owed work. Exits. The harness's supervisor runs it once per
# cycle at the cadence its spoke registry sets; this script never sleeps, loops or reads an interval.
#
# Modes
#   loop.sh                 one cycle (default)
#   loop.sh --doctor        the engine's preflight: config, env NAMES resolved (never printed), one
#                           live read-only poll per channel
#   loop.sh --stage CHANNEL ASK_TS TEXT
#                           stage ONE reply for the human GO: the engine's pre-flip guards run
#                           (marker, size, credential scan, placement) and one STAGED outbox row is
#                           written; prints the row key. Never releases, never posts.
#   loop.sh --stub-test     the acceptance test: a loopback Slack stub, a planted ask, one cycle,
#                           one staged reply; PASS only if the ask is journaled with an actionable
#                           kind, the outbox row is STAGED, and the stub counted ZERO chat.postMessage.
#
# Environment (names only; values live in the host's .env and pass in through COMMS_ENV_NAMES)
#   COMMS_ENGINE_DIR     the engine clone (default /opt/comms, the harness installer's pin)
#   CONVERSATIONS_SPOKE_WD  working directory (default /wd/conversations); state/ and the cycle record
#   COMMS_SETTINGS       settings file (default ${CONVERSATIONS_SPOKE_WD}/settings.json; generated once)
#   SLACK_BOT_TOKEN      the bot token (xoxb-…); referenced by NAME in settings.json
#   SLACK_CHANNELS       comma-separated channel ids to watch; referenced by NAME in settings.json
#   CONVERSATIONS_SPOKE_REPLY_POLICY  never | staged (default staged); `direct` is refused here and by the
#                        engine for Slack
#   COMMS_SEND_MARKER    prefix every staged reply must carry (default "[AGENT]")
#
# Writes only: ${CONVERSATIONS_SPOKE_WD}/state/** (the comms DB and the outbox, STAGED rows), last-cycle,
# cycle.log, and settings.json when none exists. Nothing to Slack, ever.
set -euo pipefail

: "${COMMS_ENGINE_DIR:=/opt/comms}"
: "${CONVERSATIONS_SPOKE_WD:=/wd/conversations}"
: "${COMMS_SETTINGS:=${CONVERSATIONS_SPOKE_WD}/settings.json}"
: "${CONVERSATIONS_SPOKE_REPLY_POLICY:=staged}"
: "${COMMS_SEND_MARKER:=[AGENT]}"

die() { echo "conversations loop: $1" >&2; exit "${2:-2}"; }   # $2 = exit code (default 2), never part of the message
now() { date -u +%Y-%m-%dT%H:%M:%SZ; }

[ -f "${COMMS_ENGINE_DIR:?}/scripts/scheduler.py" ] \
  || die "no engine at ${COMMS_ENGINE_DIR} (scripts/scheduler.py missing) — set COMMS_ENGINE_DIR to the harness's clone"
case "${CONVERSATIONS_SPOKE_REPLY_POLICY}" in
  never|staged) ;;
  *) die "CONVERSATIONS_SPOKE_REPLY_POLICY=${CONVERSATIONS_SPOKE_REPLY_POLICY} refused — this spoke stages at most; the engine refuses 'direct' for Slack" ;;
esac
mkdir -p "${CONVERSATIONS_SPOKE_WD:?}/state"

# settings.json is generated ONCE, from env NAMES: the token and the channel list never land in a file.
ensure_settings() {
  [ -f "${COMMS_SETTINGS}" ] && return 0
  [ -n "${SLACK_BOT_TOKEN:-}" ]  || die "SLACK_BOT_TOKEN is not set — export it on the host before starting the harness (its .env passes the name into the container), then restart" 3
  [ -n "${SLACK_CHANNELS:-}" ]   || die "SLACK_CHANNELS is not set (comma-separated channel ids)" 3
  local tmp; tmp="$(mktemp "${CONVERSATIONS_SPOKE_WD:?}/.settings.XXXXXX")"
  SETTINGS_OUT="$tmp" python3 -I - <<'PY'
import json, os
channels = [c.strip() for c in os.environ["SLACK_CHANNELS"].split(",") if c.strip()]
policy = os.environ.get("CONVERSATIONS_SPOKE_REPLY_POLICY", "staged")
marker = os.environ.get("COMMS_SEND_MARKER", "[AGENT]")
cfg = {
    "_note": ("generated by the conversations spoke's loop.sh from env NAMES; auth values are references, "
              "the token never lands here. Edit freely; this file is never regenerated while it exists."),
    "engine": {"state_dir": "state", "channels_dir": os.environ["COMMS_ENGINE_DIR"] + "/channels"},
    "instances": [{
        "name": "comms",
        "adapter": "slack",
        "auth": {"token": "env:SLACK_BOT_TOKEN", "channels": "env:SLACK_CHANNELS"},
        "send_marker": marker,
        "channels": [
            ({"id": c, "label": c, "poll_interval_s": 60, "triggers": ["any_message"]}
             | ({"reply_policy": policy} if policy != "never" else {}))
            for c in channels],
    }],
}
with open(os.environ["SETTINGS_OUT"], "w") as f:
    json.dump(cfg, f, indent=2); f.write("\n")
PY
  mv "${tmp:?}" "${COMMS_SETTINGS:?}"
  echo "conversations loop: wrote ${COMMS_SETTINGS} (${#SLACK_CHANNELS} chars of channel ids, policy ${CONVERSATIONS_SPOKE_REPLY_POLICY})"
}

cycle() {
  ensure_settings
  local started rc out
  started="$(now)"
  set +e
  out="$(cd "${COMMS_ENGINE_DIR}" && python3 -I scripts/scheduler.py --config "${COMMS_SETTINGS}" --once 2>&1)"
  rc=$?
  set -e
  printf '%s rc=%s %s\n' "$started" "$rc" "$(printf '%s' "$out" | grep -E '^cycle:|^sweep:|^dm-rule:|OPERATOR:|DEGRADED' | tr '\n' ' | ')" \
    >> "${CONVERSATIONS_SPOKE_WD}/cycle.log"
  if [ "$rc" -eq 0 ]; then
    now > "${CONVERSATIONS_SPOKE_WD}/last-cycle"
  fi
  printf '%s\n' "$out"
  return "$rc"
}

doctor() {
  ensure_settings
  (cd "${COMMS_ENGINE_DIR}" && python3 -I -m core.doctor --config "${COMMS_SETTINGS}")
}

stage() {
  local channel="${1:?channel id}" ask_ts="${2:?ask ts}" text="${3:?reply text}"
  ensure_settings
  STAGE_CHANNEL="$channel" STAGE_TS="$ask_ts" STAGE_TEXT="$text" COMMS_SETTINGS="${COMMS_SETTINGS}" \
    python3 -I - <<'PY'
import os, sys
sys.path.insert(0, os.environ["COMMS_ENGINE_DIR"])
from core.config import load, load_adapter_class
from core.outbox import Outbox, PolicyError, SendBlocked
cfg = load(os.environ["COMMS_SETTINGS"])
inst = cfg.instances[0]
channel, ts, text = os.environ["STAGE_CHANNEL"], os.environ["STAGE_TS"], os.environ["STAGE_TEXT"]
if inst.send_marker and not text.startswith(inst.send_marker):
    text = f"{inst.send_marker} {text}"
adapter = load_adapter_class(cfg.channels_dir, inst.adapter)(auth=inst.auth)
box = Outbox(cfg.outbox_path_for(inst.name), adapter, inst.policies(), marker=inst.send_marker)
try:
    # a reply to the ask: in a DM top-level, in a channel in the ask's thread
    thread = None if channel.startswith("D") else ts
    res = box.stage(channel, ts, text, thread_id=thread, seen_ts=ts)
except (PolicyError, SendBlocked) as ex:
    print(f"REFUSED: {ex}"); sys.exit(4)
finally:
    box.close()
print(f"STAGED key={res['key']} state={res['state']} — awaits the human GO on the write surface; nothing was sent")
PY
}

stub_test() {
  grep -q 'COMMS_SLACK_API_BASE' "${COMMS_ENGINE_DIR}/channels/slack/adapter.py" \
    || die "the engine at ${COMMS_ENGINE_DIR} has no loopback stub override (COMMS_SLACK_API_BASE); pin the engine at v0.2.0 or later" 3
  STUB_TMP="$(mktemp -d)"                       # global on purpose: the EXIT trap outlives this function
  trap 'rm -rf "${STUB_TMP:?}"' EXIT
  STUB_WD="$STUB_TMP" python3 -I - <<'PY'
import json, os, subprocess, sys
engine = os.environ["COMMS_ENGINE_DIR"]
sys.path.insert(0, engine); sys.path.insert(0, os.path.join(engine, "tests"))
from slack_stub import SlackStub                      # the engine's own loopback Slack (127.0.0.1:0)
from core.config import load, load_adapter_class
from core.journal import Journal
from core.outbox import Outbox

wd = os.environ["STUB_WD"]
stub = SlackStub(slack_escapes=True).start()
channel, ask_ts = "C_PLANTED", "1700000001.000100"
stub.seed(channel, "where is the dashboard?", user="U_PLANTED", ts=ask_ts)        # the planted ask
settings = os.path.join(wd, "settings.json")
json.dump({"engine": {"state_dir": "state", "channels_dir": engine + "/channels"},
           "instances": [{"name": "comms", "adapter": "slack", "send_marker": "[AGENT]",
                          "auth": {"token": "env:STUB_TOKEN", "channels": "env:STUB_CHANNELS"},
                          "channels": [{"id": channel, "reply_policy": "staged",
                                        "triggers": ["any_message"]}]}]},
          open(settings, "w"), indent=2)
env = dict(os.environ, STUB_TOKEN="xoxb-stub", STUB_CHANNELS=channel, COMMS_SLACK_API_BASE=stub.base,
           COMMS_SETTINGS=settings)
try:
    # one real cycle through the real scheduler and the real Slack adapter, against the stub
    run = subprocess.run([sys.executable, "-I", "scripts/scheduler.py", "--config", settings, "--once"],
                         cwd=engine, env=env, capture_output=True, text=True, timeout=120)
    print(run.stdout.strip().splitlines()[-1] if run.stdout.strip() else run.stderr[-400:])
    if run.returncode != 0:
        print("FAIL: the cycle exited", run.returncode); sys.exit(1)
    cfg = load(settings, env=env)
    j = Journal(cfg.journal_path)
    row = j.get(channel, ask_ts); j.close()
    if row is None or row["kind"] in (None, "STATEMENT"):
        print(f"FAIL: the planted ask is not journaled as an actionable ask: {dict(row) if row else None}"); sys.exit(1)
    print(f"ok: planted ask journaled, kind={row['kind']}")
    # the hub asked for a reply: stage it (the engine's guards run; nothing posts)
    inst = cfg.instances[0]
    adapter = load_adapter_class(cfg.channels_dir, inst.adapter)(auth=inst.auth, env=env)
    box = Outbox(cfg.outbox_path_for(inst.name), adapter, inst.policies(), marker=inst.send_marker)
    res = box.stage(channel, ask_ts, "[AGENT] it is at http://127.0.0.1:8502", thread_id=ask_ts, seen_ts=ask_ts)
    state = box.get(res["key"])["state"]; box.close()
    if state != "STAGED":
        print(f"FAIL: the reply is {state}, not STAGED"); sys.exit(1)
    print(f"ok: reply staged, key={res['key'][:12]}…")
    posts = [m for m, _, _ in stub.requests if m == "chat.postMessage"]
    writes = [m for m, _, _ in stub.requests if m not in ("conversations.history", "conversations.replies",
                                                           "conversations.info", "conversations.list",
                                                           "users.info", "users.list", "auth.test")]
    if posts or writes:
        print(f"FAIL: outbound posts={len(posts)} other non-read calls={writes}"); sys.exit(1)
    print(f"ok: zero chat.postMessage; {len(stub.requests)} read calls to the stub")
    print("PASS — a planted ask lands classified in the comms DB, a staged reply exists, nothing left for Slack")
finally:
    stub.stop()
PY
}

case "${1:-}" in
  "")            cycle ;;
  --doctor)      doctor ;;
  --stage)       shift; stage "$@" ;;
  --stub-test)   stub_test ;;
  -h|--help)     sed -n '4,32p' "$0" ;;
  *)             die "unknown mode ${1}; see --help" ;;
esac
